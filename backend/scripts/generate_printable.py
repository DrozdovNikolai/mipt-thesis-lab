"""Freeze Python 3.11 repr's printable characters for the Go library contract.

Pass internal/training/library_python_printable.go as the output path, then run gofmt.
"""
import argparse
import sys
import unicodedata
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    assert sys.version_info[:2] == (3, 11), sys.version
    assert unicodedata.unidata_version == "14.0.0", unicodedata.unidata_version
    ranges = []
    for codepoint in range(0x110000):
        if not chr(codepoint).isprintable():
            continue
        if ranges and ranges[-1][1] + 1 == codepoint:
            ranges[-1][1] = codepoint
        else:
            ranges.append([codepoint, codepoint])
    output = [
        "// Code generated by scripts/generate_printable.py; DO NOT EDIT.",
        "// Python 3.11 / Unicode 14.0.0 str.isprintable, used by nested JSON repr.",
        "package training", "", 'import "sort"', "",
        "func libraryPythonPrintable(r rune) bool {",
        "i := sort.Search(len(libraryPythonPrintableRanges), func(i int) bool {",
        "return libraryPythonPrintableRanges[i][1] >= r", "})",
        "return i < len(libraryPythonPrintableRanges) && libraryPythonPrintableRanges[i][0] <= r",
        "}", "", "var libraryPythonPrintableRanges = [...][2]rune{",
    ]
    output += [f"{{0x{start:X}, 0x{end:X}}}," for start, end in ranges]
    output += ["}", ""]
    args.output.write_text("\n".join(output))
    print(f"Generated {len(ranges)} printable ranges: {args.output}")


if __name__ == "__main__":
    main()
